export function buildCandidateGraph(candidateId, uploads = []) {
  const candidate = candidateProfiles.find((item) => item.id === candidateId) || candidateProfiles[0];
  const companyUploads = uploads.filter((upload) => upload.scope === 'company');
  const candidateUploads = uploads.filter((upload) => upload.scope === 'candidate' && upload.candidateId === candidate.id);

  return {
    nodes: [
      ...cloneNodes(companyBaseNodes),
      ...cloneNodes(candidateMemory[candidate.id].nodes),
      ...cloneNodes(companyUploads.map((upload) => upload.node)),
      ...cloneNodes(candidateUploads.map((upload) => upload.node)),
    ],
    links: [
      ...cloneLinks(companyBaseLinks),
      ...cloneLinks(candidateLinks[candidate.id]),
      ...cloneLinks(companyUploads.flatMap((upload) => upload.links)),
      ...cloneLinks(candidateUploads.flatMap((upload) => upload.links)),
    ],
  };
}

export function buildCompanyGraph(uploads = []) {
  const companyUploads = uploads.filter((upload) => upload.scope === 'company');

  return {
    nodes: [...cloneNodes(companyBaseNodes), ...cloneNodes(companyUploads.map((upload) => upload.node))],
    links: [...cloneLinks(companyBaseLinks), ...cloneLinks(companyUploads.flatMap((upload) => upload.links))],
  };
}

